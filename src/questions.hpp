// Перемешивает варианты ответа у вопроса и пересчитывает номер правильного.
// Question& - "ссылка": функция меняет сам вопрос, а не его копию.
inline void ShuffleAnswers(Question& q, std::mt19937& rng) {
    std::array<int, 4> order = {0, 1, 2, 3};
    std::shuffle(order.begin(), order.end(), rng);

    std::array<std::string, 4> shuffled;
    int newCorrect = 0;
    for (int i = 0; i < 4; ++i) {
        shuffled[i] = q.answers[order[i]];
        if (order[i] == q.correct) {
            newCorrect = i;  // правильный ответ переехал на позицию i
        }
    }
    q.answers = shuffled;
    q.correct = newCorrect;
}

// Выбирает count случайных вопросов из базы и перемешивает ответы в каждом.
// const ...& значит: "только читаем, не меняем и не копируем".
inline std::vector<Question> PickQuestions(const std::vector<Question>& bank,
                                           std::mt19937& rng, std::size_t count) {
    std::vector<Question> picked = bank;  // копия, чтобы не портить исходную базу
    std::shuffle(picked.begin(), picked.end(), rng);
    if (picked.size() > count) {
        picked.resize(count);
    }
    for (Question& q : picked) {  // цикл "для каждого вопроса q"
        ShuffleAnswers(q, rng);
    }
    return picked;
}
